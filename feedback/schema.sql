-- ClearSky v3: reportes + avisos
CREATE TABLE IF NOT EXISTS rep (id INTEGER PRIMARY KEY AUTOINCREMENT, ts INTEGER NOT NULL, lat REAL NOT NULL, lon REAL NOT NULL, tipo TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS idx_rep_ts ON rep (ts);
CREATE TABLE IF NOT EXISTS lim (h TEXT PRIMARY KEY, ts INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS sub (endpoint TEXT PRIMARY KEY, p256dh TEXT NOT NULL, auth TEXT NOT NULL, lat REAL NOT NULL, lon REAL NOT NULL, nombre TEXT, creado INTEGER NOT NULL, aviso INTEGER NOT NULL DEFAULT 0);
